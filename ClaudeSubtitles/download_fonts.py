#!/usr/bin/env python3
"""
Download the font pack for offline use.

The app pulls fonts straight from Google Fonts by default, which is fine as
long as you're online. Run this once and it caches every font locally into
fonts/ so the app works with no internet at all — useful if you're editing
on a machine that's offline or behind a strict firewall.

    python download_fonts.py

Every font here is SIL Open Font License or Apache 2.0: free to use in
commercial work, including released music videos.
"""

import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "fonts"

# Mirrors the FONTS list in app/presets.js
FAMILIES = [
    ("Anton", [400]), ("Bebas Neue", [400]), ("Oswald", [300, 400, 500, 600, 700]),
    ("Fjalla One", [400]), ("Teko", [400, 500, 600, 700]), ("Staatliches", [400]),
    ("Big Shoulders Display", [400, 600, 700, 800, 900]),
    ("Archivo Black", [400]), ("Montserrat", [700, 800, 900]), ("Inter", [700, 800, 900]),
    ("Poppins", [600, 700, 800, 900]), ("Chivo", [700, 800, 900]), ("Syne", [700, 800]),
    ("Unbounded", [600, 700, 800, 900]), ("Passion One", [400, 700, 900]),
    ("Alfa Slab One", [400]), ("Ultra", [400]), ("Titan One", [400]), ("Lilita One", [400]),
    ("Bowlby One", [400]), ("Luckiest Guy", [400]), ("Shrikhand", [400]),
    ("Sigmar One", [400]), ("Black Ops One", [400]), ("Righteous", [400]),
    ("Bungee", [400]), ("Bungee Inline", [400]), ("Monoton", [400]), ("Rubik Mono One", [400]),
]

# A modern UA makes Google serve woff2 (small); an old one serves ttf.
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/124.0 Safari/537.36")


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=45) as r:
        data = r.read()
    return data if binary else data.decode("utf-8")


def main():
    OUT.mkdir(exist_ok=True)
    css_parts = [
        "/* Local font pack — generated by download_fonts.py.",
        "   Delete this file to go back to loading fonts from Google. */\n",
    ]
    ok = fail = 0

    for i, (family, weights) in enumerate(FAMILIES, 1):
        fam_url = family.replace(" ", "+")
        spec = f"{fam_url}:wght@{';'.join(map(str, sorted(weights)))}" if len(weights) > 1 else fam_url
        url = f"https://fonts.googleapis.com/css2?family={spec}&display=block"
        print(f"[{i:2}/{len(FAMILIES)}] {family} ... ", end="", flush=True)
        try:
            css = fetch(url)
        except Exception as e:  # noqa: BLE001
            print(f"FAILED ({e})")
            fail += 1
            continue

        # Rewrite every remote font url to a local file we download alongside.
        n = 0
        for m in re.finditer(r"url\((https://[^)]+?)\)", css):
            src = m.group(1)
            ext = ".woff2" if ".woff2" in src else (".woff" if ".woff" in src else ".ttf")
            safe = re.sub(r"[^\w]+", "", family)
            local = f"{safe}_{abs(hash(src)) % 10**8}{ext}"
            target = OUT / local
            if not target.exists():
                try:
                    target.write_bytes(fetch(src, binary=True))
                except Exception as e:  # noqa: BLE001
                    print(f"\n      font file failed: {e}")
                    continue
            css = css.replace(src, local)
            n += 1

        css_parts.append(css)
        ok += 1
        print(f"ok ({n} file{'s' if n != 1 else ''})")

    (OUT / "fonts.css").write_text("\n".join(css_parts), encoding="utf-8")
    total_mb = sum(f.stat().st_size for f in OUT.glob("*")) / 1048576

    print()
    print(f"Done. {ok} families cached ({total_mb:.1f} MB) -> {OUT}")
    if fail:
        print(f"{fail} failed — check your connection and re-run to fill the gaps.")
    print("Restart the app and it will use the local pack automatically.")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(1)
